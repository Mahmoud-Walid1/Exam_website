import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../js/exam-pager.js', import.meta.url), 'utf8');
const { ExamPager } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
let requests = [];
let pending = [];
const pager = new ExamPager(args => { requests.push(args); return new Promise((resolve, reject) => pending.push({ resolve, reject })); }, () => {});
assert.equal(requests.length, 0, 'Constructing the pager must not fetch anything');
pager.reset({ academicYear: '1448' });
const first = pager.more();
await pager.more();
assert.equal(requests.length, 1, 'Double clicking cannot fetch duplicate pages');
assert.equal(requests[0].pageSize, 12);
pending.shift().resolve({ exams: [{ id: 'a' }], cursor: 'cursor-a', hasMore: true, simpleQuery: false });
await first;
assert.equal(requests.length, 1, 'No automatic prefetch after a successful page');
const second = pager.more();
assert.equal(requests[1].cursor, 'cursor-a');
pending.shift().resolve({ exams: [{ id: 'a' }, { id: 'b' }], cursor: 'cursor-b', hasMore: false, simpleQuery: false });
await second;
assert.deepEqual(pager.exams.map(e => e.id), ['a', 'b']);
await pager.more();
assert.equal(requests.length, 2, 'End of catalog cannot trigger additional reads');
pager.reset({ academicYear: '1447' });
const old = pager.more();
pager.reset({ academicYear: '1448', subject: 'علوم' });
const fresh = pager.more();
pending.shift().resolve({ exams: [{ id: 'stale' }], cursor: 'stale', hasMore: false });
await old;
assert.equal(pager.loading, true, 'A stale response cannot unlock the active request');
pending.shift().reject(new Error('offline'));
await fresh;
assert.equal(pager.error.message, 'offline');
assert.deepEqual(pager.exams, []);
const retry = pager.more();
assert.equal(requests.at(-1).cursor, null, 'A failed request cannot advance the cursor');
pending.shift().resolve({ exams: [{ id: 'fresh' }], cursor: 'fresh', hasMore: true, simpleQuery: true });
await retry;
assert.deepEqual(pager.exams.map(e => e.id), ['fresh']);
assert.equal(pager.simpleQuery, true);
console.log('Pagination checks passed: bounded pages, explicit fetching, deduplication, stale response handling and retry.');
